// Scopes the original WordPress/Elementor/Bootstrap CSS so it only applies inside legacy pages.
// Input: build/css-src (downloaded from embesysindia.com); output: src/styles.
import fs from 'node:fs';
import postcss from 'postcss';
import safeParser from 'postcss-safe-parser';
import { transform } from 'lightningcss';

const src = 'build/css-src';
const scopeSelector = (sel, p) => {
  sel = sel.trim();
  if (/^(html|body|:root)\b/.test(sel)) return sel.replace(/^(html\s*body|html|body|:root)/, p);
  if (sel.startsWith('.elementor-kit-371')) return sel.replace('.elementor-kit-371', p);
  if (sel.startsWith(p)) return sel;
  return `${p} ${sel}`;
};
// The original stylesheets contain unbalanced '}' that browsers ignore but bundlers reject.
function dropStrayBraces(css) {
  let out = '', depth = 0, i = 0;
  while (i < css.length) {
    const c = css[i];
    if (c === '/' && css[i + 1] === '*') { const e = css.indexOf('*/', i + 2); const j = e < 0 ? css.length : e + 2; out += css.slice(i, j); i = j; continue; }
    if (c === '"' || c === "'") { let j = i + 1; while (j < css.length && css[j] !== c) { if (css[j] === '\\') j++; j++; } out += css.slice(i, j + 1); i = j + 1; continue; }
    if (c === '{') depth++;
    if (c === '}') { if (depth === 0) { i++; continue; } depth--; }
    out += c; i++;
  }
  return out + '}'.repeat(depth);
}
const scope = (css, prefix) => {
  css = css.replace(/âœ”/g, '✔').replace(/âœ“/g, '✓'); // mojibake in the source CSS
  // fix declarations like `color: #f07700);` (stray ')' in the source) before parsing
  css = css.replace(/:\s*([^;{}()"':/]*)\)\s*;/g, ': $1;');
  const root = safeParser(css);
  root.walkRules((rule) => {
    if (rule.parent?.type === 'atrule' && /keyframes$/i.test(rule.parent.name)) return;
    rule.selectors = rule.selectors.map((s) => scopeSelector(s, prefix));
  });
  return recover(strictify(dropStrayBraces(root.toString())));
};
// Let lightningcss drop whatever invalid rules/declarations remain (same engine Vite minifies with).
function recover(css) {
  const { code, warnings } = transform({ filename: 'x.css', code: Buffer.from(css), errorRecovery: true, minify: false });
  if (warnings.length) console.warn(`  recovered ${warnings.length} invalid rule(s)`);
  return code.toString();
}
// Drop any line a strict CSS parser still rejects (broken declarations in the source stylesheets).
function strictify(css) {
  for (let n = 0; n < 200; n++) {
    try { postcss.parse(css); return css; } catch (e) {
      if (!e.line) return css;
      const lines = css.split('\n');
      console.warn(`  dropped invalid line: ${lines[e.line - 1].trim().slice(0, 80)}`);
      lines[e.line - 1] = '';
      css = lines.join('\n');
    }
  }
  return css;
}

const globalFiles = [
  'bootstrap.min.css', 'flaticon.css', 'theme-style.css', 'child-style.css', 'frontend.min.css',
  'widget-heading.min.css', 'widget-icon-list.min.css', 'widget-image.min.css', 'widget-icon-box.min.css',
  'widget-image-gallery.min.css', 'e-animation-bounce-in.min.css', 'post-371.css', 'custom.css',
];
const globalCss = globalFiles
  .filter((f) => fs.existsSync(`${src}/${f}`))
  .map((f) => `/* ${f} */\n` + scope(fs.readFileSync(`${src}/${f}`, 'utf8'), '.legacy'))
  .join('\n');
fs.writeFileSync('src/styles/legacy.css', '/* Auto-generated by scripts/scope-css.mjs: original site CSS scoped to .legacy */\n' + globalCss);

for (const f of fs.readdirSync(`${src}/pages`)) {
  const slug = f.replace(/\.css$/, '');
  const css = fs.readFileSync(`${src}/pages/${f}`, 'utf8');
  let out = '';
  try { out = scope(css, `.page-${slug}`); } catch (e) { console.warn('skip', f, e.message); }
  fs.writeFileSync(`src/styles/pages/${f}`, out);
}
console.log('scoped', fs.readdirSync('src/styles/pages').length, 'page stylesheets');
